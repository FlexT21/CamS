create table if not exists public.crossing_events (
  id bigint generated by default as identity primary key,
  occurred_at timestamptz not null default now(),
  device_id text not null,
  "user" text not null default 'Unknown',
  direction text not null check (direction in ('entrada', 'salida', 'desconocida')),
  distance_to_line double precision not null check (distance_to_line >= 0),
  recognition_distance double precision check (recognition_distance is null or recognition_distance >= 0),
  frame_id bigint not null check (frame_id >= 0),
  created_at timestamptz not null default now()
);

create index if not exists crossing_events_occurred_at_idx
  on public.crossing_events (occurred_at desc);

alter table public.crossing_events enable row level security;

